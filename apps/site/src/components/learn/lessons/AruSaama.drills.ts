const SAAMA = msg`With <et>saama</et>: <et>aru</et> understand, <et>kokku</et> meet up, <et>läbi</et> get on, <et>hakkama</et> cope.`;
const ORDER = msg`In neutral word order, the particle usually comes last. A place, time or other detail can follow it. After <et>tahan</et> or <et>pean</et>, it usually comes before the infinitive.`;

const MEANS = {
  kokku: msg`meet up`,
  labi: msg`get on`,
  aru: msg`understand`,
  hakkama: msg`cope`,
} as const;
type Means = keyof typeof MEANS;

const hear = (id: string, say: string, answer: Means): ChoiceDrill => ({
  kind: "choice",
  id,
  rule: "meaning",
  say,
  answer: { id: answer, label: MEANS[answer] },
  wrong: (Object.keys(MEANS) as Means[])
    .filter((each) => each !== answer)
    .map((each) => ({ id: each, label: MEANS[each] })),
  explain: SAAMA,
});

const particle = (
  id: string,
  base: string,
  gloss: FormDrill["gloss"],
  cue: string,
  answer: string,
  wrong: readonly string[],
  say: string,
  explain: FormDrill["explain"],
): FormDrill => ({
  kind: "form",
  id,
  rule: "meaning",
  base,
  gloss,
  cue: { et: cue },
  answers: [answer],
  wrong,
  say,
  explain,
});


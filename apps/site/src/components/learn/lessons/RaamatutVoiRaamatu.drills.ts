const heard = (
  id: string,
  rule: string,
  say: string,
  options: Record<string, DrillOption>,
  answer: string,
  explain: ChoiceDrill["explain"],
): ChoiceDrill => ({
  kind: "choice",
  id,
  rule,
  say,
  answer: options[answer] as DrillOption,
  wrong: Object.entries(options).flatMap(([key, option]) => (key === answer ? [] : [option])),
  explain,
});

